// Get all unique categories
export const getCategories = (): string[] => {
  return ['All', ...toolsData.map((cat) => cat.category)];
};

// Get all tools flat
export const getAllTools = (): ToolItem[] => {
  return toolsData.flatMap((cat) => cat.items);
};

// Get active tools only
export const getActiveTools = (): ToolItem[] => {
  return toolsData.flatMap((cat) => cat.items.filter((item) => item.isActive));
};

// Get coming soon tools
export const getComingSoonTools = (): ToolItem[] => {
  return toolsData.flatMap((cat) => cat.items.filter((item) => !item.isActive));
};

// Get tools by category
export const getToolsByCategory = (category: string): ToolItem[] => {
  if (category === 'All') return getAllTools();
  const cat = toolsData.find((c) => c.category === category);
  return cat ? cat.items : [];
};

// Get tool counts
export const getToolCounts = () => {
  const all = getAllTools();
  return {
    total: all.length,
    available: all.filter((t) => t.isActive).length,
    comingSoon: all.filter((t) => !t.isActive).length,
  };
};
